"""Build the clearly labeled, English-only UI demo PDF."""
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle


def build():
    output = Path(__file__).resolve().parents[1] / 'apps/web/public/demo-report.pdf'
    styles = getSampleStyleSheet()
    document = SimpleDocTemplate(str(output), pagesize=A4, title='Fire Atlas - demo sample', author='Fire Atlas')
    content = [
        Paragraph('FIRE ATLAS / DEMO SAMPLE', styles['Title']),
        Paragraph('Prepared example - not generated from your workspace', styles['Heading2']),
        Paragraph('This sample demonstrates the report interface. It does not represent your current selection or a new AI analysis. Scientific acceptance of the corpus is separate.', styles['BodyText']),
        Spacer(1, 24),
        Paragraph('FLEX control records', styles['Heading2']),
    ]
    rows = [['Test run', 'Initial diameter, mm', 'Burn duration, s', 'Outcome'],
            ['20CAL08', '1.69', '4.3', 'Disruption'], ['20CAL10', '1.86', '5', 'Extinction'],
            ['20CAL12', '1.61', '3.2', 'Extinction'], ['30CAL02', '2.06', '7.64', 'Extinction'],
            ['30CAL03', '1.92', '6.34', 'Extinction']]
    table = Table(rows, repeatRows=1, colWidths=[90, 130, 115, 115])
    table.setStyle(TableStyle([('BACKGROUND', (0,0), (-1,0), colors.HexColor('#102238')),
                              ('TEXTCOLOR', (0,0), (-1,0), colors.white),
                              ('GRID', (0,0), (-1,-1), .4, colors.HexColor('#d4dce4')),
                              ('TOPPADDING', (0,0), (-1,-1), 9), ('BOTTOMPADDING', (0,0), (-1,-1), 9)]))
    content += [table, Spacer(1, 24), Paragraph('Limits and provenance', styles['Heading2']),
                Paragraph('Five control records are reproduced from the specification. No trend line, prediction or causal conclusion is implied. Droplet disruption is not extinction. Missing evidence does not establish safety.', styles['BodyText']),
                Spacer(1, 14), Paragraph('Live reports are generated by the server from a fixed workspace snapshot, with original answer contexts, registered sources and explicit limitations.', styles['BodyText']),
                Spacer(1, 22), Paragraph('DEMO SAMPLE - NOT A SAFETY ASSESSMENT', styles['Heading3'])]
    document.build(content)


if __name__ == '__main__':
    build()
